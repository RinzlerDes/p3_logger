/**
 ******************************************************************************
 * @file    oled.c
 * @brief   Text driver for the 0.96" 128x64 OLED (SSD1315 on SPI1) —
 *          HAL port of the course driver (provided).
 *
 *          SWEN 563 / CMPE 663 — P2 "DG-30 DecuGuard" starter.
 *          PROVIDED DRIVER — do not change it.
 *
 *  Compare this driver with the P1 oled.c. The SSD1315 command sequence is
 *  byte-for-byte the same, and only the data path changed. P1 wrote to
 *  SPI1->DR and polled the SR flags. This driver calls HAL_SPI_Transmit()
 *  on the CubeMX-generated handle. This driver does not initialize the GPIO
 *  or the SPI. MX_GPIO_Init() and MX_SPI1_Init() own that work (refer to
 *  the .ioc).
 *
 *  Pins (CubeMX labels): PH0 = CS_DISP, PC9 = D/C_DISP, PC8 = RST_DISP,
 *  SPI1 = PA1 SCK / PA7 MOSI, 8-bit, 8 MHz, CPOL=1/CPHA=0 (mode 2, which
 *  agrees with the ST BSP and the P1 register driver).
 ******************************************************************************
 */
